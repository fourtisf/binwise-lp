#!/usr/bin/env bash
# Binwise one-command install / update for a fresh Ubuntu 22.04 or 24.04 VPS. Run as root:
#
#   curl -fsSL -o install.sh https://raw.githubusercontent.com/fourtisf/binwise-lp/refs/heads/claude/new-session-ll75nf/deploy/install.sh
#   bash install.sh binwise.org
#
# Safe to run again: it keeps the existing .env (secrets, database password), pulls the latest
# code, migrates, rebuilds and restarts. Paper mode only: LIVE_TRADING_ENABLED stays false.
#
# Optional environment variables:
#   BRANCH=<git branch>        default: claude/new-session-ll75nf
#   CERTBOT_EMAIL=<email>      for certificate expiry notices (otherwise registered without email)
#   SKIP_HTTPS=1               skip certbot (e.g. while DNS is still propagating)
set -Eeuo pipefail

DOMAIN="${1:-}"
BRANCH="${BRANCH:-claude/new-session-ll75nf}"
REPO="${REPO:-https://github.com/fourtisf/binwise-lp.git}"
APP_USER="binwise"
APP_HOME="/home/${APP_USER}"
APP_DIR="${APP_HOME}/binwise"
ENV_FILE="${APP_DIR}/.env"
NODE_MAJOR=22
PNPM_VERSION="10.28.0"

step() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
ok() { printf '\033[1;32m    ✓ %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m    ! %s\033[0m\n' "$*"; }
die() { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }
trap 'die "Failed at line $LINENO: $BASH_COMMAND"' ERR

as_app() { sudo -u "$APP_USER" -H bash -lc "cd '$APP_DIR' && $*"; }

[[ $EUID -eq 0 ]] || die "Run as root (or with sudo)."
[[ -n "$DOMAIN" ]] || die "Usage: bash install.sh <domain>   e.g. bash install.sh binwise.org"
[[ "$DOMAIN" =~ ^[a-z0-9.-]+\.[a-z]{2,}$ ]] || die "'$DOMAIN' doesn't look like a domain."
. /etc/os-release
[[ "$ID" == "ubuntu" ]] || die "This script supports Ubuntu only (found $ID)."

export DEBIAN_FRONTEND=noninteractive NEEDRESTART_MODE=a

# ---------------------------------------------------------------- swap
step "Memory"
mem_mb=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
if [[ $mem_mb -lt 4000 ]] && ! swapon --show | grep -q .; then
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  ok "Added 2 GB swap (RAM is ${mem_mb} MB; the website build needs headroom)"
else
  ok "RAM ${mem_mb} MB"
fi

# ---------------------------------------------------------------- packages
step "System packages"
apt-get update -qq
apt-get install -y -qq ca-certificates curl gnupg git openssl build-essential \
  nginx certbot python3-certbot-nginx postgresql redis-server ufw cron >/dev/null
ok "nginx, PostgreSQL, Redis, certbot, ufw"

# System-wide Node in /usr/bin (a root-only nvm install isn't visible to the app user).
if [[ ! -x /usr/bin/node ]] || [[ "$(/usr/bin/node -p 'process.versions.node.split(".")[0]')" -lt $NODE_MAJOR ]]; then
  curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | bash - >/dev/null
  apt-get install -y -qq nodejs >/dev/null
fi
ok "Node $(/usr/bin/node -v)"
# --force replaces an existing pnpm/pm2 binary instead of failing with EEXIST.
/usr/bin/npm install -g --force --no-fund --no-audit --loglevel=error "pnpm@${PNPM_VERSION}" pm2@6.0.14 >/dev/null \
  || die "Installing pnpm/pm2 failed: run '/usr/bin/npm install -g --force pnpm@${PNPM_VERSION} pm2@6.0.14' to see why"
ok "pnpm $(/usr/bin/pnpm -v)"

systemctl enable --now postgresql redis-server nginx cron >/dev/null 2>&1
ok "Services enabled"

# ---------------------------------------------------------------- user + code
step "App user and code (branch ${BRANCH})"
id "$APP_USER" >/dev/null 2>&1 || useradd -m -s /bin/bash "$APP_USER"
if [[ -d "$APP_DIR/.git" ]]; then
  sudo -u "$APP_USER" -H git -C "$APP_DIR" fetch -q origin "+refs/heads/${BRANCH}:refs/remotes/origin/${BRANCH}"
  # The server copy is never edited by hand: match the branch exactly (untracked .env is kept).
  sudo -u "$APP_USER" -H git -C "$APP_DIR" checkout -q -f -B "$BRANCH" "origin/$BRANCH"
else
  sudo -u "$APP_USER" -H git clone -q -b "$BRANCH" "$REPO" "$APP_DIR"
fi
ok "Code at $(sudo -u "$APP_USER" -H git -C "$APP_DIR" log -1 --format='%h %s')"

# ---------------------------------------------------------------- database + .env
step "Database and settings"
if [[ -f "$ENV_FILE" ]]; then
  ok "Keeping existing .env (secrets unchanged)"
  DB_PASS=$(sed -n 's#^DATABASE_URL=postgresql://binwise:\([^@]*\)@.*#\1#p' "$ENV_FILE")
  [[ -n "$DB_PASS" ]] || die "Could not read the database password from $ENV_FILE"
else
  DB_PASS=$(openssl rand -hex 24)
  umask 077
  cat > "$ENV_FILE" <<EOF
# Binwise settings. Generated by deploy/install.sh on $(date -u +%F). Never commit or share this file.

# Database / cache
DATABASE_URL=postgresql://binwise:${DB_PASS}@localhost:5432/binwise
REDIS_URL=redis://localhost:6379

# Solana. Add a Helius mainnet RPC (free key at helius.dev) for active-bin liquidity data.
RPC_URL=
RPC_WS_URL=
DEVNET_RPC_URL=
METEORA_API_URL=https://dlmm.datapi.meteora.ag
JUPITER_API_URL=https://api.jup.ag
# Free key at portal.jup.ag (recommended: keyless access is heavily rate-limited)
JUPITER_API_KEY=
JITO_BLOCK_ENGINE_URL=
JITO_TIP_LAMPORTS=10000

# Safety. Live trading needs the owner's explicit approval; keep false.
LIVE_TRADING_ENABLED=false
# Seals agent keypairs. Keep an offline copy: losing it locks any live agent wallet.
AGENT_KEY_ENCRYPTION_SECRET=$(openssl rand -base64 32)
# Kill switch over HTTP: POST /api/admin/kill with header x-admin-token
ADMIN_TOKEN=$(openssl rand -hex 16)

# Ports on 127.0.0.1 (nginx forwards to them). 3100/4100 avoid clashing with other apps on 3000/4000.
WEB_PORT=3100
API_PORT=4100
API_HOST=127.0.0.1
SESSION_SECRET=$(openssl rand -hex 32)
PUBLIC_DOMAIN=${DOMAIN}
CORS_ORIGINS=https://${DOMAIN}
API_MODE=

# Agent
AGENT_CONCURRENCY=4

# Telegram alerts (optional, from @BotFather)
TELEGRAM_BOT_TOKEN=
TELEGRAM_BOT_USERNAME=

# Website (baked in at build time; rebuild after changing)
NEXT_PUBLIC_API_URL=https://${DOMAIN}/api
NEXT_PUBLIC_WS_URL=wss://${DOMAIN}/api
NEXT_PUBLIC_RPC_URL=https://api.mainnet-beta.solana.com
EOF
  umask 022
  chown "$APP_USER:$APP_USER" "$ENV_FILE"
  ok "Created .env with fresh secrets (permissions 600)"
fi
chmod 600 "$ENV_FILE"
WEB_PORT=$(sed -n 's/^WEB_PORT=\([0-9]*\).*/\1/p' "$ENV_FILE"); WEB_PORT=${WEB_PORT:-3000}
API_PORT=$(sed -n 's/^API_PORT=\([0-9]*\).*/\1/p' "$ENV_FILE"); API_PORT=${API_PORT:-4000}
ok "Ports: website ${WEB_PORT}, API ${API_PORT} (local only)"

sudo -u postgres psql -qtAc "SELECT 1 FROM pg_roles WHERE rolname='binwise'" | grep -q 1 \
  || sudo -u postgres psql -qc "CREATE ROLE binwise LOGIN"
sudo -u postgres psql -qc "ALTER ROLE binwise WITH LOGIN PASSWORD '${DB_PASS}'"
sudo -u postgres psql -qtAc "SELECT 1 FROM pg_database WHERE datname='binwise'" | grep -q 1 \
  || sudo -u postgres psql -qc "CREATE DATABASE binwise OWNER binwise"
ok "PostgreSQL database 'binwise' (local connections only)"
redis-cli ping | grep -q PONG || die "Redis is not running"
ok "Redis running (local only)"

# ---------------------------------------------------------------- build
step "Install, migrate, build (a few minutes)"
as_app "pnpm install --frozen-lockfile --reporter=silent"
ok "Dependencies installed"
as_app "pnpm --filter @binwise/db migrate:deploy" >/dev/null
ok "Database migrated"
as_app "pnpm --filter @binwise/web build" >/tmp/binwise-web-build.log 2>&1 || { tail -30 /tmp/binwise-web-build.log; die "Website build failed (full log: /tmp/binwise-web-build.log)"; }
grep -rqs "https://${DOMAIN}/api" "$APP_DIR/apps/web/.next/static" || die "Website build doesn't contain the API address; check NEXT_PUBLIC_API_URL in .env"
ok "Website built for https://${DOMAIN}"

# ---------------------------------------------------------------- processes
step "Start processes (PM2)"
# Another app on our ports would silently receive this site's traffic: refuse instead.
for port in "$WEB_PORT" "$API_PORT"; do
  pid=$(ss -ltnpH "sport = :${port}" | grep -o 'pid=[0-9]*' | head -1 | cut -d= -f2 || true)
  if [[ -n "$pid" && "$(ps -o user= -p "$pid" | tr -d ' ')" != "$APP_USER" ]]; then
    die "Port ${port} is used by another program ($(ps -o user=,cmd= -p "$pid" | cut -c1-80)). Set WEB_PORT / API_PORT in ${ENV_FILE} to free ports and run again."
  fi
done
as_app "pm2 startOrReload deploy/ecosystem.config.cjs --update-env" >/dev/null
as_app "pm2 save" >/dev/null
/usr/bin/pm2 startup systemd -u "$APP_USER" --hp "$APP_HOME" >/dev/null
as_app "pm2 describe pm2-logrotate >/dev/null 2>&1 || pm2 install pm2-logrotate >/dev/null"
ok "web, api, collector, agent running; restart on reboot; logs rotated"

# Weekly backtest + settings search (Monday 03:00 / 03:30 server time). Never changes settings by itself.
cron_tmp=$(mktemp)
{
  crontab -u "$APP_USER" -l 2>/dev/null | grep -v '# binwise-weekly' || true
  echo "0 3 * * 1 cd $APP_DIR/apps/agent && pnpm backtest >> $APP_HOME/backtest.log 2>&1 # binwise-weekly"
  echo "30 3 * * 1 cd $APP_DIR/apps/agent && pnpm optimize --days 60 >> $APP_HOME/optimize.log 2>&1 # binwise-weekly"
} > "$cron_tmp"
crontab -u "$APP_USER" "$cron_tmp" && rm -f "$cron_tmp"
ok "Weekly reports scheduled"

# ---------------------------------------------------------------- firewall
step "Firewall"
ssh_port=$(sshd -T 2>/dev/null | awk '/^port / {print $2; exit}')
if ufw status | grep -q "Status: active"; then
  ufw allow "${ssh_port:-22}/tcp" >/dev/null
  ufw allow 'Nginx Full' >/dev/null
  ok "Firewall active: HTTP and HTTPS allowed"
else
  # Not switched on here: the server may host other services whose ports we don't know.
  warn "Firewall (ufw) is off. App ports stay private anyway (bound to 127.0.0.1); turn ufw on yourself if nothing else needs open ports."
fi

# ---------------------------------------------------------------- nginx + https
step "Nginx and HTTPS"
sed -e "s/YOUR_DOMAIN/${DOMAIN}/g" -e "s/WEB_PORT/${WEB_PORT}/g" -e "s/API_PORT/${API_PORT}/g" "$APP_DIR/deploy/nginx/binwise.conf" > /etc/nginx/sites-available/binwise
# Servers without IPv6 can't bind [::]:80.
[[ -f /proc/net/if_inet6 ]] || sed -i '/listen \[::\]/d' /etc/nginx/sites-available/binwise
ln -sf /etc/nginx/sites-available/binwise /etc/nginx/sites-enabled/binwise
rm -f /etc/nginx/sites-enabled/default
nginx -t -q || die "Nginx configuration test failed (see the message above)."
systemctl reload nginx
ok "Nginx serving ${DOMAIN}"

if [[ "${SKIP_HTTPS:-}" == "1" ]]; then
  warn "Skipped HTTPS (SKIP_HTTPS=1). The site won't work fully until HTTPS is on: re-run without it."
else
  server_ip=$(curl -fsS4 --max-time 10 https://api.ipify.org || hostname -I | awk '{print $1}')
  names=(-d "$DOMAIN")
  if [[ "$(getent ahostsv4 "$DOMAIN" | awk 'NR==1{print $1}')" != "$server_ip" ]]; then
    warn "${DOMAIN} doesn't point to this server (${server_ip}) yet. Wait for DNS (up to an hour), then run this script again to turn on HTTPS."
    NO_HTTPS=1
  else
  if [[ "$(getent ahostsv4 "www.$DOMAIN" | awk 'NR==1{print $1}')" == "$server_ip" ]]; then names+=(-d "www.$DOMAIN"); else warn "www.${DOMAIN} doesn't resolve here yet; certificate covers ${DOMAIN} only"; fi
  if [[ -n "${CERTBOT_EMAIL:-}" ]]; then email=(--email "$CERTBOT_EMAIL"); else email=(--register-unsafely-without-email); fi
  certbot --nginx --non-interactive --agree-tos --redirect "${email[@]}" "${names[@]}" >/dev/null
  ok "HTTPS on (renews automatically)"
  fi
fi

# ---------------------------------------------------------------- demo vault + checks
step "First data and demo vault"
for i in $(seq 1 36); do
  n=$(sudo -u postgres psql -d binwise -qtAc 'SELECT count(*) FROM "Token" WHERE symbol = '"'USDC'"'' 2>/dev/null || echo 0)
  [[ "${n:-0}" -gt 0 ]] && break
  sleep 5
done
if [[ "${n:-0}" -gt 0 ]]; then
  as_app "pnpm --filter @binwise/agent seed" | tail -1
  ok "Collector is storing real Meteora data"
else
  warn "No pool data after 3 minutes. Check: sudo -u $APP_USER pm2 logs binwise-collector"
  warn "Then create the demo vault: sudo -u $APP_USER -H bash -lc 'cd $APP_DIR && pnpm --filter @binwise/agent seed'"
fi

step "Health checks"
curl -fsS --max-time 10 "http://127.0.0.1:${API_PORT}/health" | grep -q '"mode":"db"' && ok "API healthy" || warn "Binwise API not answering on :${API_PORT} (pm2 logs binwise-api)"
curl -fsS --max-time 10 "http://127.0.0.1:${WEB_PORT}" | grep -qi binwise && ok "Website answering" || warn "Binwise website not answering on :${WEB_PORT} (pm2 logs binwise-web)"
curl -fsS --max-time 10 -o /dev/null "https://dlmm.datapi.meteora.ag/pools?page_size=1" && ok "Meteora API reachable" || warn "Meteora API not reachable from this server"
curl -fsS --max-time 10 -o /dev/null "https://api.jup.ag/price/v3?ids=So11111111111111111111111111111111111111112" && ok "Jupiter API reachable" \
  || warn "Jupiter price API refused the request: add a free JUPITER_API_KEY (portal.jup.ag) to .env, then: sudo -u $APP_USER pm2 restart all"
as_app "pm2 ls"

cat <<EOF

$(printf '\033[1;32m')Binwise is running at https://${DOMAIN}  (paper mode, live trading OFF)$(printf '\033[0m')
$( [[ -n "${NO_HTTPS:-}" || "${SKIP_HTTPS:-}" == "1" ]] && printf '\033[1;33m%s\033[0m' "HTTPS is NOT on yet: run this script again once ${DOMAIN} points to this server." )

  Settings file:   ${ENV_FILE}
  Back up offline: the AGENT_KEY_ENCRYPTION_SECRET and ADMIN_TOKEN lines in that file
  Logs:            sudo -u ${APP_USER} pm2 logs
  Kill switch:     sudo -u ${APP_USER} -H bash -lc 'cd ${APP_DIR} && pnpm --filter @binwise/agent kill on'
  Update later:    run the same install command again
EOF
